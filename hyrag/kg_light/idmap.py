"""kg_light/idmap.py — the LightRAG-key ↔ our-chunk-id map, built by reading storage back.

PREPLAN §5.6 is the contract; this module is where it becomes operational:

* **built from what LightRAG stored, never from what we sent.** After ingest we read
  LightRAG's own chunk rows back and match them to the ingest set **by content** — the only
  join that cannot silently drift when a hash algorithm or a normalisation changes.
* **bijectivity is asserted, not hoped for**: every stored chunk resolves to exactly one of
  our chunks, and every one of our chunks is accounted for. A count that agrees while the
  text differs is exactly the failure the gate is written to catch, so the comparison is
  content-equality and not a row count.
* **an unmapped reference is a stop-the-line error.** Entities and relations carry
  `source_id` strings (chunk keys joined by `<SEP>`); the moment one of them is not in the
  map, Phase 2's `bridge` would either drop it or — worse — guess. `unmapped_source_ids`
  enumerates every reference the graph holds so the check can print a **zero** rather than
  claim one.

The map is written to `parsed/kg_light_idmap.json` (gitignored, regenerable) so a bridge run
can be audited after the fact.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone

import psycopg
from lightrag.constants import GRAPH_FIELD_SEP
from psycopg.rows import dict_row

from hyrag.baseline.store import connect
from hyrag.kg_light import config

_JSON = {"ensure_ascii": False, "sort_keys": True, "separators": (",", ":")}


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


# ---------------------------------------------------------------- reading LightRAG's store


def stored_chunks() -> list[dict]:
    """Every chunk row LightRAG holds, with the fields the map and the gate need."""
    with connect() as conn, conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            """
            SELECT id, content, file_path, full_doc_id, chunk_order_index, tokens
            FROM lightrag_doc_chunks
            WHERE workspace = %s
            ORDER BY full_doc_id, chunk_order_index
            """,
            (config.WORKSPACE,),
        )
        return cur.fetchall()


def stored_counts() -> dict:
    """Row counts for every store the row wrote — the numbers that go in the report.

    Read straight from Postgres rather than from the pipeline's own counters: a count taken
    from the thing that wrote the rows is not a check. Vector tables carry a model suffix
    (`LIGHTRAG_VDB_ENTITY_bge_m3_1024d`) — generated by LightRAG from the embedding model —
    so the lookup goes through the catalogue by prefix rather than naming a table that the
    next model change would silently rename.
    """
    counts: dict[str, int | None] = {}
    with connect() as conn, conn.cursor() as cur:
        for label, prefix in (
            ("documents", "lightrag_doc_full"),
            ("chunks", "lightrag_doc_chunks"),
            ("entity_vectors", "lightrag_vdb_entity"),
            ("relation_vectors", "lightrag_vdb_relation"),
        ):
            counts[label] = _count_tables(cur, prefix)
    counts["graph_nodes"], counts["graph_edges"] = graph_counts()
    counts["doc_status"] = _doc_status_counts()
    return counts


def _count_tables(cur, prefix: str) -> int:
    """Rows in every public table whose name starts with `prefix`, workspace-scoped."""
    cur.execute(
        "SELECT table_name FROM information_schema.tables "
        "WHERE table_schema = 'public' AND table_name LIKE %s",
        (f"{prefix}%",),
    )
    total = 0
    for (table,) in cur.fetchall():
        cur.execute(f'SELECT count(*) FROM "{table}" WHERE workspace = %s', (config.WORKSPACE,))
        total += cur.fetchone()[0]
    return total


def _doc_status_counts() -> dict:
    with connect() as conn, conn.cursor() as cur:
        cur.execute(
            "SELECT status, count(*) FROM lightrag_doc_status WHERE workspace = %s GROUP BY status",
            (config.WORKSPACE,),
        )
        return {status: count for status, count in cur.fetchall()}


def graph_path():
    """Where NetworkXStorage persists the graph — note the workspace subdirectory.

    File-based storages put their data under `working_dir/<workspace>/` (lightrag.utils
    → `validate_workspace`), so with `workspace="hyrag"` the file is one level deeper than
    `working_dir` itself. This cost one `graph_nodes: None` in a smoke run's summary.
    """
    return config.WORKING_DIR / config.WORKSPACE / "graph_chunk_entity_relation.graphml"


def graph_counts() -> tuple[int | None, int | None]:
    path = graph_path()
    if not path.is_file():
        return None, None
    import networkx as nx

    graph = nx.read_graphml(path)
    return graph.number_of_nodes(), graph.number_of_edges()


# ---------------------------------------------------------------- the map


def build() -> dict:
    """Read LightRAG's chunk rows back and write the map. Raises on any mismatch."""
    ours = config.our_chunks()
    our_by_content: dict[str, dict] = {}
    for record in ours:
        if record["content"] in our_by_content:
            raise ValueError(
                f"{record['chunk_id']}: duplicate content in the ingest set — the chunker's "
                f"dedupe is supposed to make this impossible (§5.6)"
            )
        our_by_content[record["content"]] = record

    rows = stored_chunks()
    mapping: dict[str, str] = {}
    problems: dict[str, list[str]] = {"unresolved": [], "file_path_mismatch": []}

    for row in rows:
        record = our_by_content.get(row["content"])
        if record is None:
            problems["unresolved"].append(row["id"])
            continue
        if row["file_path"] != record["file"]:
            problems["file_path_mismatch"].append(
                f"{row['id']}: stored {row['file_path']!r}, expected {record['file']!r}"
            )
        mapping[row["id"]] = record["chunk_id"]

    mapped_ours = set(mapping.values())
    unmapped_ours = [record["chunk_id"] for record in ours if record["chunk_id"] not in mapped_ours]
    # A bijection needs both directions, and the second is the one a row count hides: N keys
    # could still resolve to N *different* chunks while one of our chunks never arrived.
    bijective = (
        len(mapping) == len(rows) == len(ours)
        and len(mapped_ours) == len(ours)
        and not unmapped_ours
        and not problems["unresolved"]
    )

    document = {
        "type": "kg_light_idmap",
        "lightrag_rev": config.LIGHTRAG_REV,
        "built_at": _now(),
        "workspace": config.WORKSPACE,
        "counts": {"lightrag_chunks": len(rows), "our_chunks": len(ours), "mapped": len(mapping)},
        "bijective": bijective,
        "unmapped_our_chunks": unmapped_ours,
        "problems": problems,
        # The map's direction is lightrag_key -> our chunk_id, because LightRAG's key is the
        # one that comes back at query time (§5.6).
        "map": dict(sorted(mapping.items())),
    }
    config.IDMAP_PATH.write_text(json.dumps(document, **_JSON) + "\n", encoding="utf-8")
    return document


def load_map() -> dict:
    document = json.loads(config.IDMAP_PATH.read_text(encoding="utf-8"))
    return document["map"]


# ---------------------------------------------------------------- the references


def graph_references() -> dict[str, list[str]]:
    """Every `source_id` the graph holds, per node and per edge.

    Read from the persisted graphml rather than from the in-memory object: the file is what
    a later run (and the bridge) will read, so checking the file checks the artifact.
    """
    import networkx as nx

    graph = nx.read_graphml(graph_path())
    references: dict[str, list[str]] = {"nodes": [], "edges": [], "missing": []}
    for _node, attributes in graph.nodes(data=True):
        raw = attributes.get("source_id")
        if raw:
            references["nodes"].extend(str(raw).split(GRAPH_FIELD_SEP))
        else:
            references["missing"].append(f"node {attributes.get('entity_id')}")
    for _src, _tgt, attributes in graph.edges(data=True):
        raw = attributes.get("source_id")
        if raw:
            references["edges"].extend(str(raw).split(GRAPH_FIELD_SEP))
        else:
            references["missing"].append(f"edge {attributes.get('src_id')}->{attributes.get('tgt_id')}")
    return references


def unmapped_source_ids(mapping: dict | None = None) -> dict:
    """The gate's second half: count the references that do not resolve. Must be zero."""
    mapping = load_map() if mapping is None else mapping
    references = graph_references()
    all_references = references["nodes"] + references["edges"]
    unmapped = sorted({reference for reference in all_references if reference not in mapping})
    return {
        "node_references": len(references["nodes"]),
        "edge_references": len(references["edges"]),
        "total_references": len(all_references),
        "distinct": len(set(all_references)),
        "unmapped": unmapped,
        "attributes_without_source_id": references["missing"],
    }
